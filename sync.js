/** @returns {{jamo:string, text:string}|null} */
export function hintFor(jamo, role) {
  if (!jamo) return null;
  if (VOWEL[jamo]) return { jamo, text: VOWEL[jamo] };
  if (CONSONANT[jamo]) {
    if (jamo === 'ㅇ' && role !== 'jong') return null; // 첫소리 ㅇ은 소리가 없음
    const prefix = role === 'jong' ? `받침 ${jamo}: ` : '';
    return { jamo, text: prefix + CONSONANT[jamo].replace(/^받침 ㅇ은 /, '') };
  }
  return null;
}
